use iced::widget::svg::Handle;

macro_rules! icons {
    ($($fn_name:ident => $file:literal),* $(,)?) => {
        $(pub fn $fn_name() -> Handle {
            Handle::from_memory(include_bytes!(concat!("../assets/icons/", $file, ".svg")).as_slice())
        })*
    };
}

